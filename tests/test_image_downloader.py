async def test_process_image_paths_preserves_local_then_downloaded_order(
    downloader: ImageDownloader, tmp_path: Path
) -> None:
    """Local paths keep their order and come first; downloads follow in URL order."""
    first = tmp_path / "first.jpg"
    second = tmp_path / "second.jpg"
    first.write_bytes(_JPEG_BYTES)
    second.write_bytes(_JPEG_BYTES)

    downloaded: list[str] = []

    async def fake_download_images(urls: list[str]) -> list[dict]:
        downloaded.extend(urls)
        return [
            {
                "originalUrl": url,
                "localPath": f"/cache/{index}.jpg",
                "cached": False,
                "fileSize": 1,
            }
            for index, url in enumerate(urls)
        ]

    downloader.download_images = fake_download_images  # type: ignore[assignment]

    result = await downloader.process_image_paths(
        [str(first), "https://e.com/x.jpg", str(second), "https://e.com/y.jpg"]
    )

    assert result == [str(first), str(second), "/cache/0.jpg", "/cache/1.jpg"]
    assert downloaded == ["https://e.com/x.jpg", "https://e.com/y.jpg"]


async def test_download_images_aggregates_failures(downloader: ImageDownloader) -> None:
    async def fake_download_image(url: str) -> dict:
        if url.endswith("bad.jpg"):
            raise InvalidImageError(f"boom for {url}")
        return {"originalUrl": url, "localPath": "/x.jpg", "cached": False, "fileSize": 1}

    downloader.download_image = fake_download_image  # type: ignore[assignment]

    with pytest.raises(InvalidImageError) as excinfo:
        await downloader.download_images(
            ["https://e.com/ok.jpg", "https://e.com/bad.jpg", "https://e.com/bad.jpg"]
        )

    error = excinfo.value
    assert error.message.startswith("Failed to download 2 of 3 images:")
    assert "https://e.com/bad.jpg: boom for https://e.com/bad.jpg" in error.message
    assert error.context["failedCount"] == 2
    assert error.context["successCount"] == 1
    assert error.context["totalCount"] == 3


async def test_cached_file_is_reused(downloader: ImageDownloader) -> None:
    url = "https://example.com/cached.jpg"
    cached_path = Path(downloader.get_save_dir()) / downloader._generate_file_name(url)
    cached_path.write_bytes(_JPEG_BYTES)

    result = await downloader.download_image(url)

    assert result["cached"] is True
    assert result["localPath"] == str(cached_path)
    assert result["fileSize"] == len(_JPEG_BYTES)


def test_get_image_downloader_reuses_instance_per_dir(tmp_path: Path) -> None:
    first = get_image_downloader(str(tmp_path / "one"))
    assert get_image_downloader(str(tmp_path / "one")) is first
    assert get_image_downloader(str(tmp_path / "two")) is not first
