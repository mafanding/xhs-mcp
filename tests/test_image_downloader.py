"""Image downloader behaviour, ported from tests/integration/image-downloader.test.js.

Cache filenames are checked against ``tests/name_oracle.json``, generated by the
original Node implementation, because a filename change would silently
invalidate every user's existing download cache.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from xhs_mcp.shared.errors import InvalidImageError
from xhs_mcp.shared.image_downloader import ImageDownloader, get_image_downloader

_NAME_ORACLE = json.loads((Path(__file__).parent / "name_oracle.json").read_text())

_JPEG_BYTES = b"\xff\xd8\xff" + b"\x00" * 20
_PNG_BYTES = b"\x89PNG\r\n\x1a\n" + b"\x00" * 20
_GIF_BYTES = b"GIF89a" + b"\x00" * 20
_WEBP_BYTES = b"RIFF\x00\x00\x00\x00WEBP" + b"\x00" * 20
_BMP_BYTES = b"BM" + b"\x00" * 20


@pytest.fixture
def downloader(tmp_path: Path) -> ImageDownloader:
    return ImageDownloader(str(tmp_path / "temp_images"))


@pytest.mark.parametrize(
    ("path", "expected"),
    [
        ("https://example.com/a.jpg", True),
        ("http://example.com/a.jpg", True),
        ("HTTPS://EXAMPLE.COM/A.JPG", True),
        ("  https://example.com/a.jpg  ", True),
        ("./local/a.jpg", False),
        ("/abs/path/a.jpg", False),
        ("C:\\images\\a.jpg", False),
        ("ftp://example.com/a.jpg", False),
        ("", False),
    ],
)
def test_is_image_url(path: str, expected: bool) -> None:
    assert ImageDownloader.is_image_url(path) is expected


@pytest.mark.parametrize(("url", "expected_name"), sorted(_NAME_ORACLE.items()))
def test_generate_file_name_matches_node_oracle(
    downloader: ImageDownloader, url: str, expected_name: str
) -> None:
    assert downloader._generate_file_name(url) == expected_name


def test_generate_file_name_is_stable(downloader: ImageDownloader) -> None:
    url = "https://example.com/photo.png"
    assert downloader._generate_file_name(url) == downloader._generate_file_name(url)


@pytest.mark.parametrize(
    ("data", "expected_valid", "expected_ext"),
    [
        (_JPEG_BYTES, True, "jpg"),
        (_PNG_BYTES, True, "png"),
        (_GIF_BYTES, True, "gif"),
        (_WEBP_BYTES, True, "webp"),
        (_BMP_BYTES, True, "bmp"),
        (b"<html>not an image</html>", False, ""),
        (b"short", False, ""),
        (b"", False, ""),
    ],
)
def test_validate_image_data(data: bytes, expected_valid: bool, expected_ext: str) -> None:
    is_valid, extension = ImageDownloader._validate_image_data(data)
    assert is_valid is expected_valid
    assert extension == expected_ext


